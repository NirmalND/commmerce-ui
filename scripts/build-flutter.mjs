// Generates the Flutter package's tokens and icons from the same sources as the web packages:
//   packages/tokens/src/tokens.source.json -> flutter/commmerce_ui/lib/src/generated/tokens.g.dart
//   packages/icons/src/icons.json         -> flutter/commmerce_ui/lib/src/generated/icons.g.dart
// Run after changing tokens or icons:  npm run flutter:generate
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const out = join(root, 'flutter/commmerce_ui/lib/src/generated');
mkdirSync(out, { recursive: true });
const src = JSON.parse(readFileSync(join(root, 'packages/tokens/src/tokens.source.json'), 'utf8'));
const icons = JSON.parse(readFileSync(join(root, 'packages/icons/src/icons.json'), 'utf8'));
const camel = (s) => s.replace(/[-.]([a-z0-9])/g, (_, c) => c.toUpperCase());
const HEADER = '// GENERATED by scripts/build-flutter.mjs from the Commmerce UI sources. Do not edit.\n// ignore_for_file: constant_identifier_names, public_member_api_docs, deprecated_member_use_from_same_package\n';
// Tokens whose usage starts with "Deprecated" get a Dart @Deprecated annotation, so analyzers flag every use.
const dep = (t) => (/^Deprecated/.test(t.usage ?? '') ? `  @Deprecated('${t.usage.replace(/\n/g, ' ').replace(/'/g, "\\'")}')\n` : '');

function color(v) {
  let m = v.match(/^#([0-9a-f]{3}|[0-9a-f]{6}|[0-9a-f]{8})$/i);
  if (m) {
    let h = m[1];
    if (h.length === 3) h = [...h].map((c) => c + c).join('');
    if (h.length === 6) h = 'ff' + h; else h = h.slice(6) + h.slice(0, 6);
    return `Color(0x${h.toUpperCase()})`;
  }
  m = v.match(/^rgba?\(([^)]+)\)$/);
  if (m) {
    const [r, g, b, a = 1] = m[1].split(',').map((x) => parseFloat(x));
    return `Color.fromRGBO(${r}, ${g}, ${b}, ${a})`;
  }
  throw new Error(`unsupported colour ${v}`);
}

// ---- colours: one class, a light and a dark instance ----
const themes = src.color.themes.map((t) => t.id);
const colorTokens = src.color.tokens;
const valueFor = (t, theme) => (typeof t.value === 'string' ? t.value : t.value[theme] ?? t.value[themes[0]]);
const fields = colorTokens.map((t) => `  /// ${t.usage.replace(/\n/g, ' ')}\n${dep(t)}  final Color ${camel(t.name)};`).join('\n');
const instance = (theme) => `  static const ${theme} = CmColors(\n${colorTokens.map((t) => `    ${camel(t.name)}: ${color(valueFor(t, theme))},`).join('\n')}\n  );`;
const lerp = colorTokens.map((t) => `      ${camel(t.name)}: Color.lerp(${camel(t.name)}, other.${camel(t.name)}, t)!,`).join('\n');
const copy = colorTokens.map((t) => `${camel(t.name)}: ${camel(t.name)}`).join(', ');

// ---- spacing, radius, type, shadow ----
const px = (v) => parseFloat(String(v));
const space = src.spacing.tokens.map((t) => `  /// ${t.usage}\n${dep(t)}  static const double ${camel(t.name.replace('space-', 's'))} = ${px(t.value)};`).join('\n');
const radius = src.radius.tokens.map((t) => `  /// ${t.usage}\n  static const double ${camel(t.name.replace('radius-', ''))} = ${px(t.value)};`).join('\n');
const weight = (w) => `FontWeight.w${Math.round(Number(String(w).split(' ')[0]) / 100) * 100}`;
const typeGroups = src.type.groups.map((g) => {
  const styles = g.styles.map((s) => `  /// ${s.usage ?? ''}\n  static const TextStyle ${camel(s.name.replace(/-resp$/, ''))} = TextStyle(fontFamily: cmFontFamily, package: cmFontPackage, fontSize: ${px(s.fontSize)}, height: ${Number(s.lineHeight) || px(s.lineHeight) / px(s.fontSize)}, fontWeight: ${weight(s.fontWeight)});`).join('\n');
  return `/// ${g.name} type ramp.\nabstract final class CmType${g.name === 'Desktop' ? '' : g.name} {\n${styles}\n}`;
}).join('\n\n');
const shadowTok = (src.shadow?.tokens ?? []).filter((t) => (typeof t.value === 'string' ? t.value : t.value.light) !== 'none');
const shadow = shadowTok.map((t) => {
  const v = typeof t.value === 'string' ? t.value : t.value.light;
  // One BoxShadow per layer ("0 1px 2px rgba(…), 0 1px 3px rgba(…)"); lengths may omit px when 0, spread is optional.
  const layers = v.split(/,(?![^(]*\))/).map((layer) => {
    const m = layer.trim().match(/^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?(?:\s+(-?[\d.]+)(?:px)?)?\s+(rgba?\([^)]+\)|#[0-9a-f]+)$/i);
    if (!m) throw new Error(`flutter: can't read shadow ${t.name}: ${layer}`);
    return `BoxShadow(offset: Offset(${m[1]}, ${m[2]}), blurRadius: ${m[3]}, spreadRadius: ${m[4] ?? 0}, color: ${color(m[5])})`;
  });
  return `  /// ${t.usage}\n${dep(t)}  static const List<BoxShadow> ${camel(/^shadow-\d/.test(t.name) ? t.name.replace('shadow-', 's') : t.name.replace('shadow-', ''))} = [${layers.join(', ')}];`;
}).join('\n');
// ---- control heights, icon sizes, motion ----
const sizeTok = src.size?.tokens ?? [];
const sizeGroup = (prefix) => sizeTok.filter((t) => t.name.startsWith(prefix)).map((t) => `  /// ${t.usage}\n  static const double ${camel(t.name.slice(prefix.length))} = ${px(t.value)};`).join('\n');
const motionTok = src.motion?.tokens ?? [];
const motion = motionTok.map((t) => {
  if (t.name.startsWith('duration-')) {
    const ms = /ms$/.test(t.value) ? parseFloat(t.value) : parseFloat(t.value) * 1000;
    return `  /// ${t.usage} ${t.value}.\n  static const Duration ${camel(t.name.replace('duration-', ''))} = Duration(milliseconds: ${ms});`;
  }
  const m = t.value.match(/^cubic-bezier\(([^)]+)\)$/);
  if (!m) throw new Error(`flutter: can't read motion ${t.name}: ${t.value}`);
  const [a, b, c2, d] = m[1].split(',').map((x) => parseFloat(x));
  return `  /// ${t.usage} ${t.value}.\n  static const Cubic ${camel(t.name.replace('easing-', ''))} = Cubic(${a}, ${b}, ${c2}, ${d});`;
}).join('\n');
const tracking = (src.letterSpacing?.tokens ?? []).find((t) => t.name === 'tracking-caps');

writeFileSync(join(out, 'tokens.g.dart'), `${HEADER}
import 'package:flutter/animation.dart';
import 'package:flutter/painting.dart';

/// Font family bundled with this package (Poppins 400, 500, 600).
const String cmFontFamily = 'Poppins';
/// Package that holds the bundled font.
const String cmFontPackage = 'commmerce_ui';
/// Letter spacing for uppercase labels, as a fraction of the font size (${tracking?.value ?? '0.16em'}).
const double cmTrackingCaps = ${tracking ? parseFloat(tracking.value) : 0.16};

/// Every Commmerce colour token, in one theme. Use [CmColors.light] or [CmColors.dark].
class CmColors {
  const CmColors({
${colorTokens.map((t) => `    required this.${camel(t.name)},`).join('\n')}
  });

${fields}

${themes.map(instance).join('\n\n')}

  /// Interpolates between two themes (for animated theme changes).
  CmColors lerp(CmColors other, double t) => CmColors(
${lerp}
      );

  /// A copy with the same values (override fields with named arguments as needed).
  CmColors copy() => CmColors(${copy});
}

/// Spacing on the 4px grid (docs Foundations > Scale): s4 to s64. s10, s15, s22 and s30 are deprecated since 1.5.
abstract final class CmSpace {
${space}
}

/// Corner radii.
abstract final class CmRadius {
${radius}
}

${typeGroups}

/// Shadows: only for things that float (menus, popovers, dialogs, toasts). Cards and panels are flat.
abstract final class CmShadow {
${shadow}
}

/// Control heights (docs Foundations > Scale). On touch screens every control is at least [touch] tall.
abstract final class CmControlHeight {
${sizeGroup('control-height-')}
}

/// Icon sizes.
abstract final class CmIconSize {
${sizeGroup('icon-size-')}
}

/// Motion: durations and the easing for every transition. Turn animations off when
/// \`MediaQuery.disableAnimationsOf(context)\` is true (see \`cmDuration\` in theme.dart).
abstract final class CmMotion {
${motion}
}
`);

// ---- icons ----
const dotted = ['more', 'drag'];
writeFileSync(join(out, 'icons.g.dart'), `${HEADER}
/// SVG path data for every Commmerce line icon, on a 24×24 grid.
const Map<String, String> cmIconPaths = {
${Object.entries(icons).map(([n, d]) => `  '${n}': '${d}',`).join('\n')}
};

/// Icons drawn as dots, which use a heavier stroke so the dots read.
const Set<String> cmDottedIcons = {${dotted.map((d) => `'${d}'`).join(', ')}};

/// Names of every icon, for autocomplete: \`CmIcon(CmIcons.cart)\`.
abstract final class CmIcons {
${Object.keys(icons).map((n) => `  static const String ${camel(n)} = '${n}';`).join('\n')}
}
`);
console.log(`flutter: ${colorTokens.length} colours, ${src.spacing.tokens.length} spacing, ${Object.keys(icons).length} icons -> ${out}`);
